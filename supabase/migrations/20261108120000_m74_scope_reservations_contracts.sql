-- Replace the legacy customer-only newest-reservation validator. The exact
-- source IDs are checked above; this function retains lifecycle/status rules.
CREATE OR REPLACE FUNCTION public.validate_contract_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF TG_OP = 'UPDATE'
    AND (NEW.status IS DISTINCT FROM OLD.status
      OR NEW.is_active IS DISTINCT FROM OLD.is_active
      OR NEW.void_reason IS DISTINCT FROM OLD.void_reason
      OR NEW.voided_at IS DISTINCT FROM OLD.voided_at
      OR NEW.voided_by IS DISTINCT FROM OLD.voided_by
      OR NEW.cancel_reason IS DISTINCT FROM OLD.cancel_reason
      OR NEW.cancelled_at IS DISTINCT FROM OLD.cancelled_at
      OR NEW.cancelled_by IS DISTINCT FROM OLD.cancelled_by)
    AND NOT public.is_admin_user() THEN
    RAISE EXCEPTION 'Only Admin and Super Admin users can change contract lifecycle status.';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.project_id IS NULL AND NEW.project_id IS NULL THEN
    RETURN NEW;
  END IF;
  RETURN NEW;
END;
$function$;

