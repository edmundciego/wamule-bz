CREATE OR REPLACE FUNCTION public.link_approved_application_customer_v1(
  p_tenant_id uuid,
  p_application_id bigint,
  p_customer_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_actor_tenant uuid;
  v_application record;
  v_previous_customer bigint;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'An authenticated Admin or Super Admin is required.' USING ERRCODE = '42501';
  END IF;
  SELECT ap.role::text, ap.tenant_id INTO v_role, v_actor_tenant
  FROM public.admin_profiles ap WHERE ap.user_id = v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin')
     OR NOT public.user_has_tenant_access(p_tenant_id)
     OR (v_role = 'Admin' AND v_actor_tenant IS DISTINCT FROM p_tenant_id) THEN
    RAISE EXCEPTION 'Only the tenant Admin or verified Super Admin may link an application customer.' USING ERRCODE = '42501';
  END IF;

  SELECT a.id, a.tenant_id, a.project_id, a.phase_id, a.parcel_id,
         a.application_kind::text AS application_kind, a.status::text AS status
  INTO v_application
  FROM public.applications a
  WHERE a.id = p_application_id AND a.tenant_id = p_tenant_id
  FOR UPDATE;
  IF NOT FOUND OR v_application.application_kind <> 'land_purchase'
     OR v_application.status <> 'Approved'
     OR NOT public.workspace_scope_is_active(p_tenant_id, v_application.project_id, v_application.phase_id)
     OR v_application.parcel_id IS NULL THEN
    RAISE EXCEPTION 'Customer linking requires an approved land-purchase application and active verified sale scope.' USING ERRCODE = '23514';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.customers c WHERE c.id = p_customer_id AND c.tenant_id = p_tenant_id) THEN
    RAISE EXCEPTION 'The selected customer must belong to the verified tenant.' USING ERRCODE = '23503';
  END IF;
  SELECT ca.customer_id INTO v_previous_customer
  FROM public.customer_applications ca
  WHERE ca.tenant_id = p_tenant_id AND ca.application_id = p_application_id AND ca.is_primary
  FOR UPDATE;
  IF v_previous_customer IS NULL THEN
    RAISE EXCEPTION 'The approved application has no current primary customer relation.' USING ERRCODE = '23514';
  END IF;
  IF v_previous_customer = p_customer_id THEN
    RETURN jsonb_build_object('status','reused','tenant_id',p_tenant_id,'project_id',v_application.project_id,
      'phase_id',v_application.phase_id,'application_id',p_application_id,'customer_id',p_customer_id);
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.lot_reservations r
    WHERE r.tenant_id = p_tenant_id AND r.application_id = p_application_id
      AND r.customer_id IS DISTINCT FROM p_customer_id
  ) OR EXISTS (
    SELECT 1 FROM public.contracts c
    WHERE c.tenant_id = p_tenant_id AND c.application_id = p_application_id
      AND c.customer_id IS DISTINCT FROM p_customer_id
  ) THEN
    RAISE EXCEPTION 'Link the canonical customer before creating reservations or contracts for this application.' USING ERRCODE = '23514';
  END IF;

  UPDATE public.customer_applications
  SET is_primary = false, relationship_role = 'legacy_origin'
  WHERE tenant_id = p_tenant_id AND application_id = p_application_id
    AND customer_id = v_previous_customer AND is_primary;
  INSERT INTO public.customer_applications(
    tenant_id, customer_id, application_id, relationship_role, is_primary,
    linked_at, linked_by, link_source
  ) VALUES (
    p_tenant_id, p_customer_id, p_application_id, 'additional_sale', true,
    now(), v_actor, 'explicit_admin_link'
  )
  ON CONFLICT (tenant_id, customer_id, application_id)
  DO UPDATE SET relationship_role = 'additional_sale', is_primary = true,
    linked_at = EXCLUDED.linked_at, linked_by = EXCLUDED.linked_by,
    link_source = 'explicit_admin_link';

  INSERT INTO public.audit_events(
    tenant_id, target_tenant_id, target_project_id, target_phase_id,
    entity_type, entity_id, action, title, summary, metadata, actor_user_id
  ) VALUES (
    p_tenant_id, p_tenant_id, v_application.project_id, v_application.phase_id,
    'application', p_application_id::text, 'updated', 'Customer link changed',
    'An authorized workspace administrator selected the primary customer for an approved sale.',
    jsonb_build_object('event_code','customer_application_primary_link_changed','source','admin_rpc'), v_actor
  );
  RETURN jsonb_build_object('status','linked','tenant_id',p_tenant_id,'project_id',v_application.project_id,
    'phase_id',v_application.phase_id,'application_id',p_application_id,
    'customer_id',p_customer_id,'previous_customer_id',v_previous_customer);
END;
$function$;
REVOKE ALL ON FUNCTION public.link_approved_application_customer_v1(uuid,bigint,bigint) FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.link_approved_application_customer_v1(uuid,bigint,bigint) TO authenticated;

