-- A contract's parcel is authoritative scope evidence. Do not derive scope
-- from its customer, current workspace, or tenant default.
UPDATE public.contracts c
SET project_id = p.project_id,
    phase_id = p.phase_id
FROM public.parcels p
WHERE p.id = c.parcel_id
  AND p.tenant_id = c.tenant_id
  AND p.project_id IS NOT NULL
  AND p.phase_id IS NOT NULL
  AND c.project_id IS NULL
  AND c.phase_id IS NULL;

-- Reservations are backfilled only when every present scoped parent agrees.
-- Customer-only rows and rows whose parent lacks scope remain unresolved.
WITH sale_scope_sources AS (
  SELECT r.id AS reservation_id, a.project_id, a.phase_id
  FROM public.lot_reservations r
  JOIN public.applications a ON a.id = r.application_id AND a.tenant_id = r.tenant_id
  WHERE r.application_id IS NOT NULL AND a.application_kind = 'land_purchase'
  UNION ALL
  SELECT r.id, p.project_id, p.phase_id
  FROM public.lot_reservations r
  JOIN public.parcels p ON p.id = r.parcel_id AND p.tenant_id = r.tenant_id
  WHERE r.parcel_id IS NOT NULL
  UNION ALL
  SELECT r.id, l.project_id, l.phase_id
  FROM public.lot_reservations r
  JOIN public.leads l ON l.id = r.lead_id AND l.tenant_id = r.tenant_id
  WHERE r.lead_id IS NOT NULL
  UNION ALL
  SELECT r.id, a.project_id, a.phase_id
  FROM public.lot_reservations r
  JOIN public.applications a ON a.id = r.converted_application_id AND a.tenant_id = r.tenant_id
  WHERE r.converted_application_id IS NOT NULL AND a.application_kind = 'land_purchase'
  UNION ALL
  SELECT r.id, c.project_id, c.phase_id
  FROM public.lot_reservations r
  JOIN public.contracts c ON c.id = r.converted_contract_id AND c.tenant_id = r.tenant_id
  WHERE r.converted_contract_id IS NOT NULL
  UNION ALL
  SELECT r.id, c.project_id, c.phase_id
  FROM public.lot_reservations r
  JOIN public.transactions t ON t.id = r.payment_id AND t.tenant_id = r.tenant_id
  JOIN public.contracts c ON c.id = t.contract_id AND c.tenant_id = t.tenant_id
  WHERE r.payment_id IS NOT NULL AND t.contract_id IS NOT NULL
),
consistent_sale_scope AS (
  SELECT reservation_id,
         min(project_id::text)::uuid AS project_id,
         min(phase_id::text)::uuid AS phase_id
  FROM sale_scope_sources
  GROUP BY reservation_id
  HAVING bool_and(project_id IS NOT NULL AND phase_id IS NOT NULL)
     AND count(DISTINCT project_id::text || ':' || phase_id::text) = 1
)
UPDATE public.lot_reservations r
SET project_id = s.project_id,
    phase_id = s.phase_id
FROM consistent_sale_scope s
WHERE r.id = s.reservation_id
  AND r.project_id IS NULL
  AND r.phase_id IS NULL;

-- Keep an exact authorizing application/reservation on existing contracts only
-- when the evidence is unique and agrees with the already derived parcel scope.
UPDATE public.contracts c
SET application_id = a.id
FROM public.customers customer
JOIN public.applications a ON a.id = customer.application_id AND a.tenant_id = customer.tenant_id
WHERE c.customer_id = customer.id
  AND c.tenant_id = customer.tenant_id
  AND c.project_id = a.project_id
  AND c.phase_id = a.phase_id
  AND c.parcel_id = a.parcel_id
  AND a.status = 'Approved'
  AND a.application_kind = 'land_purchase'
  AND c.application_id IS NULL;

WITH matching_reservations AS (
  SELECT c.id AS contract_id, r.id AS reservation_id,
         count(*) OVER (PARTITION BY c.id) AS match_count
  FROM public.contracts c
  JOIN public.lot_reservations r
    ON r.tenant_id = c.tenant_id
   AND r.project_id = c.project_id
   AND r.phase_id = c.phase_id
   AND r.customer_id = c.customer_id
   AND r.parcel_id = c.parcel_id
   AND r.status IN ('reserved','deposit_pending','deposit_submitted','deposit_confirmed','converted_to_contract')
  WHERE c.project_id IS NOT NULL AND c.phase_id IS NOT NULL
    AND c.reservation_id IS NULL
)
UPDATE public.contracts c
SET reservation_id = m.reservation_id
FROM matching_reservations m
WHERE c.id = m.contract_id AND m.match_count = 1;

