CREATE OR REPLACE FUNCTION public.guard_phase_scoped_sale_record()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_role text;
  v_tenant_id uuid;
  v_project_id uuid;
  v_phase_id uuid;
  v_customer_id bigint;
  v_parcel_id bigint;
  v_application_id bigint;
  v_application_kind text;
  v_reservation_id uuid;
  v_converted_contract_id bigint;
  v_lead_id uuid;
  v_payment_id bigint;
  v_linked_tenant uuid;
  v_linked_project uuid;
  v_linked_phase uuid;
  v_linked_customer bigint;
  v_linked_parcel bigint;
  v_linked_application_id bigint;
  v_parcel_status text;
BEGIN
  SELECT ap.role::text INTO v_role
  FROM public.admin_profiles ap
  WHERE ap.user_id = auth.uid();

  IF v_role IS NULL THEN
    RAISE EXCEPTION 'A current Wamule profile is required for a sale-scope write.' USING ERRCODE = '42501';
  END IF;

  IF TG_TABLE_NAME = 'lot_reservations' THEN
    v_tenant_id := NEW.tenant_id;
    v_project_id := NEW.project_id;
    v_phase_id := NEW.phase_id;
    v_customer_id := NEW.customer_id;
    v_parcel_id := NEW.parcel_id;
    v_application_id := NEW.application_id;
    v_converted_contract_id := NEW.converted_contract_id;
    v_lead_id := NEW.lead_id;
    v_payment_id := NEW.payment_id;

    IF v_role NOT IN ('Admin','Staff','Super Admin') THEN
      RAISE EXCEPTION 'This role cannot create or update a reservation.' USING ERRCODE = '42501';
    END IF;
    IF TG_OP = 'INSERT' AND v_project_id IS NULL AND v_phase_id IS NULL THEN
      -- A caller may omit the copied scope only when one exact linked parent
      -- supplies it. Never use the tenant default as an inference source.
      IF v_application_id IS NOT NULL THEN
        SELECT a.project_id,a.phase_id INTO v_project_id,v_phase_id
        FROM public.applications a WHERE a.id = v_application_id AND a.tenant_id = v_tenant_id
          AND a.application_kind = 'land_purchase';
      ELSIF v_parcel_id IS NOT NULL THEN
        SELECT p.project_id,p.phase_id INTO v_project_id,v_phase_id
        FROM public.parcels p WHERE p.id = v_parcel_id AND p.tenant_id = v_tenant_id;
      ELSIF v_lead_id IS NOT NULL THEN
        SELECT l.project_id,l.phase_id INTO v_project_id,v_phase_id
        FROM public.leads l WHERE l.id = v_lead_id AND l.tenant_id = v_tenant_id;
      END IF;
      IF v_project_id IS NULL OR v_phase_id IS NULL THEN
        RAISE EXCEPTION 'A new reservation requires explicit scope or one scoped application, parcel or lead.' USING ERRCODE = '23514';
      END IF;
      NEW.project_id := v_project_id;
      NEW.phase_id := v_phase_id;
    ELSIF TG_OP = 'INSERT' AND (v_project_id IS NULL OR v_phase_id IS NULL) THEN
      RAISE EXCEPTION 'Reservation project and phase must be supplied together.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.project_id IS NOT NULL
       AND (OLD.tenant_id IS DISTINCT FROM NEW.tenant_id
         OR OLD.project_id IS DISTINCT FROM NEW.project_id
         OR OLD.phase_id IS DISTINCT FROM NEW.phase_id) THEN
      RAISE EXCEPTION 'A reservation sale scope cannot be reassigned.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.project_id IS NULL
       AND (NEW.project_id IS NOT NULL OR NEW.phase_id IS NOT NULL) THEN
      RAISE EXCEPTION 'An unresolved legacy reservation requires a separately reviewed scope assignment.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND EXISTS (
      SELECT 1 FROM public.contracts c
      WHERE c.reservation_id = OLD.id
        AND (c.tenant_id IS DISTINCT FROM NEW.tenant_id
          OR c.project_id IS DISTINCT FROM NEW.project_id
          OR c.phase_id IS DISTINCT FROM NEW.phase_id
          OR c.customer_id IS DISTINCT FROM NEW.customer_id
          OR c.parcel_id IS DISTINCT FROM NEW.parcel_id
          OR c.application_id IS DISTINCT FROM NEW.application_id)
    ) THEN
      RAISE EXCEPTION 'A reservation referenced by a contract cannot change its sale links.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.project_id IS NULL AND NEW.project_id IS NULL
       AND (OLD.tenant_id IS DISTINCT FROM NEW.tenant_id
         OR OLD.application_id IS DISTINCT FROM NEW.application_id
         OR OLD.parcel_id IS DISTINCT FROM NEW.parcel_id
         OR OLD.lead_id IS DISTINCT FROM NEW.lead_id
         OR OLD.customer_id IS DISTINCT FROM NEW.customer_id
         OR OLD.payment_id IS DISTINCT FROM NEW.payment_id
         OR OLD.converted_application_id IS DISTINCT FROM NEW.converted_application_id
         OR OLD.converted_contract_id IS DISTINCT FROM NEW.converted_contract_id) THEN
      RAISE EXCEPTION 'An unresolved legacy reservation cannot acquire or change sale links until its scope is reviewed.' USING ERRCODE = '23514';
    END IF;
    IF v_project_id IS NULL AND v_phase_id IS NULL AND TG_OP = 'UPDATE' THEN
      RETURN NEW;
    END IF;
    IF v_project_id IS NULL OR v_phase_id IS NULL
       OR NOT public.workspace_scope_exists(v_tenant_id, v_project_id, v_phase_id) THEN
      RAISE EXCEPTION 'Reservation project and phase do not resolve to one tenant workspace.' USING ERRCODE = '23514';
    END IF;
    IF NOT public.user_has_tenant_access(v_tenant_id)
       OR (v_role = 'Staff' AND NOT public.user_has_project_access(v_tenant_id, v_project_id, v_phase_id)) THEN
      RAISE EXCEPTION 'The caller cannot write reservations in this workspace.' USING ERRCODE = '42501';
    END IF;
    IF TG_OP = 'INSERT' AND NOT public.workspace_scope_is_active(v_tenant_id, v_project_id, v_phase_id) THEN
      RAISE EXCEPTION 'New reservations require an active tenant and phase.' USING ERRCODE = '23514';
    END IF;

    IF v_customer_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.customers c WHERE c.id = v_customer_id AND c.tenant_id = v_tenant_id
    ) THEN
      RAISE EXCEPTION 'Reservation customer is outside its tenant.' USING ERRCODE = '23503';
    END IF;
    IF v_application_id IS NOT NULL THEN
        SELECT a.tenant_id, a.project_id, a.phase_id, a.application_kind
        INTO v_linked_tenant, v_linked_project, v_linked_phase, v_application_kind
        FROM public.applications a WHERE a.id = v_application_id;
        IF NOT FOUND OR v_linked_tenant IS DISTINCT FROM v_tenant_id
           OR v_linked_project IS DISTINCT FROM v_project_id
           OR v_linked_phase IS DISTINCT FROM v_phase_id
           OR v_application_kind IS DISTINCT FROM 'land_purchase' THEN
        RAISE EXCEPTION 'Reservation application must be a land-purchase application in the same phase.' USING ERRCODE = '23514';
        END IF;
        IF v_customer_id IS NOT NULL AND NOT EXISTS (
          SELECT 1 FROM public.customer_applications ca
          WHERE ca.customer_id = v_customer_id AND ca.tenant_id = v_tenant_id
            AND ca.application_id = v_application_id AND ca.is_primary
        ) THEN
          RAISE EXCEPTION 'Reservation customer must be the approved primary customer for its application.' USING ERRCODE = '23514';
        END IF;
      END IF;
    IF NEW.converted_application_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.applications a
      WHERE a.id = NEW.converted_application_id AND a.tenant_id = v_tenant_id
        AND a.project_id = v_project_id AND a.phase_id = v_phase_id
        AND a.application_kind = 'land_purchase'
    ) THEN
      RAISE EXCEPTION 'Converted application must be a land-purchase application in the same phase.' USING ERRCODE = '23514';
    END IF;
    IF v_parcel_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.parcels p
      WHERE p.id = v_parcel_id AND p.tenant_id = v_tenant_id
        AND p.project_id = v_project_id AND p.phase_id = v_phase_id
    ) THEN
      RAISE EXCEPTION 'Reservation parcel must belong to the same project and phase.' USING ERRCODE = '23514';
    END IF;
    IF v_lead_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.leads l
      WHERE l.id = v_lead_id AND l.tenant_id = v_tenant_id
        AND l.project_id = v_project_id AND l.phase_id = v_phase_id
    ) THEN
      RAISE EXCEPTION 'Reservation lead must belong to the same project and phase.' USING ERRCODE = '23514';
    END IF;
    IF v_converted_contract_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.contracts c
      WHERE c.id = v_converted_contract_id AND c.tenant_id = v_tenant_id
        AND c.project_id = v_project_id AND c.phase_id = v_phase_id
        AND (v_customer_id IS NULL OR c.customer_id = v_customer_id)
        AND (v_parcel_id IS NULL OR c.parcel_id = v_parcel_id)
    ) THEN
      RAISE EXCEPTION 'Converted contract must match reservation customer, parcel, project and phase.' USING ERRCODE = '23514';
    END IF;
    IF v_payment_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.transactions t
      LEFT JOIN public.contracts c ON c.id = t.contract_id AND c.tenant_id = t.tenant_id
      WHERE t.id = v_payment_id AND t.tenant_id = v_tenant_id
        AND (v_customer_id IS NULL OR t.customer_id = v_customer_id)
        AND t.contract_id IS NOT NULL
        AND c.id IS NOT NULL AND c.project_id = v_project_id AND c.phase_id = v_phase_id
    ) THEN
      RAISE EXCEPTION 'Reservation payment must match the tenant/customer and, when linked to a contract, the same phase.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;

  -- Contracts are created/changed by Admin in the verified target only.
  v_tenant_id := NEW.tenant_id;
  v_project_id := NEW.project_id;
  v_phase_id := NEW.phase_id;
  v_customer_id := NEW.customer_id;
  v_parcel_id := NEW.parcel_id;
  v_application_id := NEW.application_id;
  v_reservation_id := NEW.reservation_id;

  IF TG_OP = 'INSERT' AND v_project_id IS NULL AND v_phase_id IS NULL THEN
    SELECT p.project_id,p.phase_id INTO v_project_id,v_phase_id
    FROM public.parcels p WHERE p.id = v_parcel_id AND p.tenant_id = v_tenant_id;
    IF v_project_id IS NULL OR v_phase_id IS NULL THEN
      RAISE EXCEPTION 'A new contract requires an exact parcel project and phase.' USING ERRCODE = '23514';
    END IF;
    NEW.project_id := v_project_id;
    NEW.phase_id := v_phase_id;
  END IF;

  IF v_role NOT IN ('Admin','Super Admin') OR NOT public.user_has_tenant_access(v_tenant_id) THEN
    RAISE EXCEPTION 'Only a Tenant Admin or verified Super Admin can create or update a contract.' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.project_id IS NOT NULL
     AND (OLD.tenant_id IS DISTINCT FROM NEW.tenant_id
       OR OLD.project_id IS DISTINCT FROM NEW.project_id
       OR OLD.phase_id IS DISTINCT FROM NEW.phase_id) THEN
    RAISE EXCEPTION 'A contract sale scope cannot be reassigned.' USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.project_id IS NULL
     AND (NEW.project_id IS NOT NULL OR NEW.phase_id IS NOT NULL) THEN
    RAISE EXCEPTION 'An unresolved legacy contract requires a separately reviewed scope assignment.' USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.project_id IS NULL AND NEW.project_id IS NULL
     AND (OLD.tenant_id IS DISTINCT FROM NEW.tenant_id
       OR OLD.customer_id IS DISTINCT FROM NEW.customer_id
       OR OLD.parcel_id IS DISTINCT FROM NEW.parcel_id
       OR OLD.application_id IS DISTINCT FROM NEW.application_id
       OR OLD.reservation_id IS DISTINCT FROM NEW.reservation_id) THEN
    RAISE EXCEPTION 'An unresolved legacy contract cannot acquire or change sale links until its scope is reviewed.' USING ERRCODE = '23514';
  END IF;
  IF v_project_id IS NULL AND v_phase_id IS NULL AND TG_OP = 'UPDATE' THEN
    RETURN NEW;
  END IF;
  IF v_project_id IS NULL OR v_phase_id IS NULL
     OR NOT public.workspace_scope_exists(v_tenant_id, v_project_id, v_phase_id) THEN
    RAISE EXCEPTION 'A new or scoped contract requires one verified tenant/project/phase.' USING ERRCODE = '23514';
  END IF;
  IF NOT public.workspace_scope_is_active(v_tenant_id, v_project_id, v_phase_id) THEN
    RAISE EXCEPTION 'A new sale contract requires an active tenant and phase.' USING ERRCODE = '23514';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.customers c WHERE c.id = v_customer_id AND c.tenant_id = v_tenant_id) THEN
    RAISE EXCEPTION 'Contract customer must belong to the same tenant.' USING ERRCODE = '23503';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.parcels p WHERE p.id = v_parcel_id AND p.tenant_id = v_tenant_id
                 AND p.project_id = v_project_id AND p.phase_id = v_phase_id) THEN
    RAISE EXCEPTION 'Contract parcel must belong to the same project and phase.' USING ERRCODE = '23514';
  END IF;

  IF v_application_id IS NULL AND v_reservation_id IS NULL THEN
    SELECT min(matches.id) INTO v_application_id
    FROM (
      SELECT a.id
      FROM public.customer_applications ca
      JOIN public.applications a ON a.id = ca.application_id AND a.tenant_id = ca.tenant_id
      WHERE ca.customer_id = v_customer_id AND ca.tenant_id = v_tenant_id AND ca.is_primary
        AND a.project_id = v_project_id AND a.phase_id = v_phase_id
        AND a.application_kind = 'land_purchase'
        AND a.status = 'Approved'::public.application_status
        AND a.parcel_id = v_parcel_id
    ) AS matches
    HAVING count(*) = 1;
    IF v_application_id IS NOT NULL THEN
      NEW.application_id := v_application_id;
    END IF;
  END IF;

  IF v_application_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.applications a
    WHERE a.id = v_application_id AND a.tenant_id = v_tenant_id
      AND a.project_id = v_project_id AND a.phase_id = v_phase_id
      AND a.application_kind = 'land_purchase'
      AND a.status = 'Approved'::public.application_status
      AND a.parcel_id = v_parcel_id
      AND EXISTS (SELECT 1 FROM public.customer_applications ca
                  WHERE ca.customer_id = v_customer_id AND ca.tenant_id = v_tenant_id
                    AND ca.application_id = a.id AND ca.is_primary)
  ) THEN
    RAISE EXCEPTION 'Contract application must be approved for this exact parcel and phase.' USING ERRCODE = '23514';
  END IF;

  IF v_reservation_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.lot_reservations r
    WHERE r.id = v_reservation_id AND r.tenant_id = v_tenant_id
      AND r.project_id = v_project_id AND r.phase_id = v_phase_id
      AND r.customer_id = v_customer_id AND r.parcel_id = v_parcel_id
      AND (r.application_id IS NULL OR v_application_id IS NULL OR r.application_id = v_application_id)
      AND (TG_OP = 'UPDATE' OR r.status IN ('reserved','deposit_pending','deposit_submitted','deposit_confirmed'))
  ) THEN
    RAISE EXCEPTION 'Contract reservation must authorize the same customer, parcel and phase.' USING ERRCODE = '23514';
  END IF;
  IF v_application_id IS NULL AND v_reservation_id IS NULL THEN
    RAISE EXCEPTION 'An exact approved application or same-phase reservation must authorize the contract.' USING ERRCODE = '23514';
  END IF;

  IF NEW.is_active IS NOT TRUE OR NEW.status <> 'active' THEN
    RETURN NEW;
  END IF;
  SELECT p.status::text INTO v_parcel_status
  FROM public.parcels p
  WHERE p.id = v_parcel_id AND p.tenant_id = v_tenant_id
    AND p.project_id = v_project_id AND p.phase_id = v_phase_id
  FOR UPDATE;
  IF v_parcel_status = 'Sold' AND (TG_OP = 'INSERT' OR NEW.parcel_id IS DISTINCT FROM OLD.parcel_id) THEN
    RAISE EXCEPTION 'Cannot create an active contract for a sold lot.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.contract_void_resolutions r
             WHERE r.parcel_id = v_parcel_id AND r.tenant_id = v_tenant_id AND r.status = 'pending') THEN
    RAISE EXCEPTION 'Lot resolution is required before another contract can use this parcel.';
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.guard_phase_scoped_sale_record() FROM PUBLIC, anon, authenticated, service_role;

