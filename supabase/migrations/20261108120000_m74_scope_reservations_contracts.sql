CREATE OR REPLACE FUNCTION public.can_read_contract_scope_metadata(
  p_tenant_id uuid, p_project_id uuid, p_phase_id uuid
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT COALESCE(
    public.user_has_tenant_access(p_tenant_id)
    AND public.workspace_scope_exists(p_tenant_id,p_project_id,p_phase_id)
    AND (
      (ap.role::text IN ('Admin','Super Admin'))
      OR (ap.role::text = 'Read Only' AND public.user_has_project_access(p_tenant_id,p_project_id,p_phase_id))
    ), false
  )
  FROM public.admin_profiles ap WHERE ap.user_id = auth.uid();
$function$;
REVOKE ALL ON FUNCTION public.can_read_contract_scope_metadata(uuid,uuid,uuid) FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.can_read_contract_scope_metadata(uuid,uuid,uuid) TO authenticated;

CREATE OR REPLACE VIEW public.contract_scope_metadata AS
SELECT c.id, c.tenant_id, c.project_id, c.phase_id, c.customer_id, c.parcel_id,
       c.status, c.is_active, c.created_at,
       customer.first_name AS customer_first_name,
       customer.last_name AS customer_last_name,
       parcel.lot_number
FROM public.contracts c
JOIN public.customers customer ON customer.id = c.customer_id AND customer.tenant_id = c.tenant_id
JOIN public.parcels parcel ON parcel.id = c.parcel_id AND parcel.tenant_id = c.tenant_id
 AND parcel.project_id = c.project_id AND parcel.phase_id = c.phase_id
WHERE public.can_read_contract_scope_metadata(c.tenant_id,c.project_id,c.phase_id);
REVOKE ALL ON public.contract_scope_metadata FROM PUBLIC, anon, service_role;
GRANT SELECT ON public.contract_scope_metadata TO authenticated;

-- The old routine can release a shared customer's other phase reservation.
-- Keep its implementation private behind a same-phase checked public wrapper.
ALTER FUNCTION public.release_alternate_reservations(uuid,uuid[],text)
  RENAME TO release_alternate_reservations_v1_internal;
REVOKE ALL ON FUNCTION public.release_alternate_reservations_v1_internal(uuid,uuid[],text)
  FROM PUBLIC, anon, authenticated, service_role;
CREATE FUNCTION public.release_alternate_reservations(
  p_primary_reservation_id uuid,
  p_reservation_ids uuid[],
  p_release_reason text
)
RETURNS TABLE (released_reservation_ids uuid[], skipped_reservations jsonb)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_primary public.lot_reservations%ROWTYPE;
BEGIN
  IF NOT public.can_write_admin_data() THEN
    RAISE EXCEPTION 'Missing permission to release reservations.' USING ERRCODE = '42501';
  END IF;
  SELECT r.* INTO v_primary FROM public.lot_reservations r
  WHERE r.id = p_primary_reservation_id FOR SHARE;
  IF NOT FOUND OR v_primary.project_id IS NULL OR v_primary.phase_id IS NULL THEN
    RAISE EXCEPTION 'Primary reservation has no verified project/phase scope.' USING ERRCODE = '23514';
  END IF;
  IF NOT public.user_has_project_access(v_primary.tenant_id,v_primary.project_id,v_primary.phase_id) THEN
    RAISE EXCEPTION 'The caller cannot release reservations in this phase.' USING ERRCODE = '42501';
  END IF;
  IF p_reservation_ids IS NULL OR cardinality(p_reservation_ids) = 0 THEN
    RAISE EXCEPTION 'Select at least one reservation to release.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.lot_reservations r
    WHERE r.id = ANY(p_reservation_ids)
      AND (r.tenant_id IS DISTINCT FROM v_primary.tenant_id
        OR r.project_id IS DISTINCT FROM v_primary.project_id
        OR r.phase_id IS DISTINCT FROM v_primary.phase_id)
  ) THEN
    RAISE EXCEPTION 'Alternate reservations must belong to the primary sale phase.' USING ERRCODE = '23514';
  END IF;
  RETURN QUERY SELECT * FROM public.release_alternate_reservations_v1_internal(
    p_primary_reservation_id,p_reservation_ids,p_release_reason
  );
END;
$function$;
REVOKE ALL ON FUNCTION public.release_alternate_reservations(uuid,uuid[],text) FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.release_alternate_reservations(uuid,uuid[],text) TO authenticated;

COMMIT;
