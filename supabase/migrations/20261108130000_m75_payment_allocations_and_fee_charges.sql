    WHERE a.tenant_id=c.tenant_id AND a.contract_id=c.id AND a.currency=c.currency
      AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided')),0)
    + COALESCE((SELECT sum(s.amount) FROM public.reservation_contract_settlements s
      WHERE s.tenant_id=c.tenant_id AND s.contract_id=c.id AND s.currency=c.currency),0))::numeric(12,2) AS total_posted_land_paid,
  greatest(c.final_purchase_price-(COALESCE((SELECT sum(a.amount) FROM public.transaction_allocations a
    JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
    WHERE a.tenant_id=c.tenant_id AND a.contract_id=c.id AND a.currency=c.currency
      AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided')),0)
    + COALESCE((SELECT sum(s.amount) FROM public.reservation_contract_settlements s
      WHERE s.tenant_id=c.tenant_id AND s.contract_id=c.id AND s.currency=c.currency),0)),0)::numeric(12,2) AS remaining_balance,
  c.project_id,c.phase_id,c.currency,
  COALESCE((SELECT sum(s.amount) FROM public.reservation_contract_settlements s
    WHERE s.tenant_id=c.tenant_id AND s.contract_id=c.id AND s.currency=c.currency),0)::numeric(12,2) AS reservation_settled_credit
FROM public.contracts c
WHERE c.is_active=true AND c.status='active';
GRANT SELECT ON public.contract_financial_summary TO authenticated;

CREATE OR REPLACE VIEW public.customer_balance_view
WITH (security_invoker = true)
AS
SELECT cu.id AS customer_id,trim(cu.first_name||' '||cu.last_name) AS customer_name,
  COALESCE((SELECT sum(s.total_posted_land_paid) FROM public.contract_financial_summary s WHERE s.customer_id=cu.id),0)::numeric AS land_paid,
  COALESCE((SELECT sum(a.amount) FROM public.transaction_allocations a
    JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
    WHERE a.customer_id=cu.id AND a.fee_charge_id IS NOT NULL
      AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided')),0)::numeric AS community_paid,
  COALESCE((SELECT sum(s.remaining_balance) FROM public.contract_financial_summary s WHERE s.customer_id=cu.id),0)::numeric AS land_balance
FROM public.customers cu;
GRANT SELECT ON public.customer_balance_view TO authenticated;

COMMENT ON VIEW public.contract_financial_summary IS
  'Contract balance uses net exact-currency allocations and reservation settlement credits; it never sums parent receipt amounts.';
COMMENT ON VIEW public.customer_balance_view IS
  'Customer balance view uses posted allocation rows for fee collections; fee defaults and reminders do not count as owed or paid amounts.';

-- Parent receipt rows are visible in full only to Admin/Super Admin. Read Only
-- users use the exact-phase allocation RPC, which never reveals a split parent
-- total or another phase's allocation.
DROP POLICY IF EXISTS "Transactions readable by internal users" ON public.transactions;
DROP POLICY IF EXISTS transactions_admin_finance_read_m75 ON public.transactions;
CREATE POLICY transactions_admin_finance_read_m75 ON public.transactions
FOR SELECT TO authenticated
USING (public.user_has_tenant_access(tenant_id)
  AND EXISTS (SELECT 1 FROM public.admin_profiles ap WHERE ap.user_id=auth.uid()
    AND (ap.role::text='Super Admin' OR (ap.role::text='Admin' AND ap.tenant_id=tenant_id))));
DROP POLICY IF EXISTS "Transactions writable by admin staff" ON public.transactions;
DROP POLICY IF EXISTS "Internal writers can create transactions" ON public.transactions;
DROP POLICY IF EXISTS transactions_admin_insert_m75 ON public.transactions;
CREATE POLICY transactions_admin_insert_m75 ON public.transactions
FOR INSERT TO authenticated WITH CHECK (
  status='needs_review'
  AND public.user_has_tenant_access(tenant_id)
  AND EXISTS (SELECT 1 FROM public.admin_profiles ap WHERE ap.user_id=auth.uid()
    AND (ap.role::text='Super Admin' OR (ap.role::text='Admin' AND ap.tenant_id=tenant_id)))
);
GRANT INSERT ON public.transactions TO authenticated;
REVOKE UPDATE ON public.transactions FROM authenticated;

COMMIT;
