CREATE OR REPLACE FUNCTION public.validate_transaction_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_contract_customer_id bigint;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.status = 'posted' AND NEW.status = 'voided'
       AND COALESCE(current_setting('app.payment_correction', true), '') = 'void_payment_record'
       AND COALESCE(current_setting('app.payment_allocation_write', true), '') = 'on'
       AND ROW(NEW.tenant_id,NEW.customer_id,NEW.contract_id,NEW.amount,NEW.currency,NEW.allocation_version,
               NEW.transaction_type,NEW.collection_method,NEW.bank_reference,NEW.manual_receipt_number,
               NEW.receipt_date,NEW.receipt_issued_by,NEW.receipt_notes,NEW.notes,NEW.reversal_of_transaction_id)
           IS NOT DISTINCT FROM
           ROW(OLD.tenant_id,OLD.customer_id,OLD.contract_id,OLD.amount,OLD.currency,OLD.allocation_version,
               OLD.transaction_type,OLD.collection_method,OLD.bank_reference,OLD.manual_receipt_number,
               OLD.receipt_date,OLD.receipt_issued_by,OLD.receipt_notes,OLD.notes,OLD.reversal_of_transaction_id) THEN
      RETURN NEW;
    END IF;
    IF OLD.status = 'posted' OR NEW.status = 'posted' OR NEW.status = 'voided' THEN
      RAISE EXCEPTION 'Posted receipts can change only through the atomic void operation.' USING ERRCODE = '42501';
    END IF;
  END IF;
  IF NEW.bank_reference IS NOT NULL THEN
    NEW.bank_reference := NULLIF(upper(btrim(NEW.bank_reference)), '');
  END IF;
  IF NEW.status = 'needs_review' THEN
    IF NEW.collection_method = 'Cash'::public.collection_method THEN
      NEW.bank_reference := NULL;
    END IF;
    IF NEW.contract_id IS NOT NULL THEN
      SELECT c.customer_id INTO v_contract_customer_id
      FROM public.contracts c
      WHERE c.id = NEW.contract_id AND c.tenant_id = NEW.tenant_id;
      IF NOT FOUND OR v_contract_customer_id IS DISTINCT FROM NEW.customer_id THEN
        RAISE EXCEPTION 'Review receipt contract must belong to its tenant and customer.' USING ERRCODE = '23514';
      END IF;
    END IF;
    NEW.allocation_version := 'legacy';
    RETURN NEW;
  END IF;
  IF NEW.status <> 'posted' THEN
    RAISE EXCEPTION 'New receipts must be posted through the allocation operation or staged as needs_review.' USING ERRCODE = '23514';
  END IF;
  IF COALESCE(current_setting('app.payment_allocation_write', true), '') <> 'on'
     OR NEW.allocation_version <> 'allocations_v1' THEN
    RAISE EXCEPTION 'Posted receipts must use record_payment_with_allocations_v1().' USING ERRCODE = '42501';
  END IF;
  IF NEW.collection_method = 'Online Transfer'::public.collection_method
     AND NULLIF(btrim(NEW.bank_reference), '') IS NULL THEN
    RAISE EXCEPTION 'Bank reference is required for online transfer payments.' USING ERRCODE = '23514';
  END IF;
  IF NEW.collection_method = 'Cash'::public.collection_method THEN
    NEW.bank_reference := NULL;
  END IF;
  IF NEW.currency IS NULL OR NEW.currency !~ '^[A-Z]{3}$' THEN
    RAISE EXCEPTION 'A three-letter uppercase currency is required for posted receipts.' USING ERRCODE = '23514';
  END IF;
  IF NEW.contract_id IS NOT NULL THEN
    SELECT c.customer_id INTO v_contract_customer_id
    FROM public.contracts c
    WHERE c.id = NEW.contract_id AND c.tenant_id = NEW.tenant_id;
    IF NOT FOUND OR v_contract_customer_id IS DISTINCT FROM NEW.customer_id THEN
      RAISE EXCEPTION 'Receipt contract must belong to its tenant and customer.' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.validate_transaction_write() FROM PUBLIC, anon, authenticated, service_role;

