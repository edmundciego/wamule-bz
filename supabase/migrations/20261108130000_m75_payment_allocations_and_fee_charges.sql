GRANT EXECUTE ON FUNCTION public.record_payment_with_allocations_v1(bigint,numeric,text,public.transaction_type,public.collection_method,text,text,date,text,text,text,bigint,jsonb) TO authenticated;

CREATE OR REPLACE FUNCTION public.void_payment_record(p_transaction_id bigint,p_reason text)
RETURNS public.transactions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_profile_tenant uuid;
  v_payment public.transactions%ROWTYPE;
  v_updated public.transactions%ROWTYPE;
  v_reservation_id uuid;
  v_reservation_cash_after numeric(12,2);
  v_reservation_credit numeric(12,2);
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'An authenticated Admin or Super Admin is required.' USING ERRCODE='42501'; END IF;
  SELECT ap.role::text,ap.tenant_id
    INTO v_role,v_profile_tenant
  FROM public.admin_profiles ap WHERE ap.user_id=v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin') THEN RAISE EXCEPTION 'Only an Admin can void a payment.' USING ERRCODE='42501'; END IF;
  SELECT * INTO v_payment FROM public.transactions t WHERE t.id=p_transaction_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Payment record not found.'; END IF;
  IF NOT public.user_has_tenant_access(v_payment.tenant_id)
     OR (v_role='Admin' AND v_profile_tenant IS DISTINCT FROM v_payment.tenant_id) THEN
    RAISE EXCEPTION 'The payment is outside the verified Admin target.' USING ERRCODE='42501';
  END IF;
  IF NULLIF(btrim(p_reason),'') IS NULL OR v_payment.status<>'posted' THEN
    RAISE EXCEPTION 'A posted payment and a reason are required.' USING ERRCODE='23514';
  END IF;
  FOR v_reservation_id IN
    SELECT DISTINCT a.reservation_id FROM public.transaction_allocations a
    WHERE a.transaction_id=v_payment.id AND a.tenant_id=v_payment.tenant_id
      AND a.reservation_id IS NOT NULL AND a.allocation_kind='applied'
  LOOP
    SELECT COALESCE(sum(a.amount),0) INTO v_reservation_cash_after
    FROM public.transaction_allocations a
    JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
    WHERE a.reservation_id=v_reservation_id AND a.tenant_id=v_payment.tenant_id
      AND a.currency IS NOT DISTINCT FROM v_payment.currency
      AND a.allocation_kind IN ('applied','reversal') AND t.status='posted'
      AND a.transaction_id<>v_payment.id;
    SELECT COALESCE(sum(s.amount),0) INTO v_reservation_credit
    FROM public.reservation_contract_settlements s
    WHERE s.reservation_id=v_reservation_id AND s.tenant_id=v_payment.tenant_id
      AND s.currency IS NOT DISTINCT FROM v_payment.currency;
    IF v_reservation_credit>v_reservation_cash_after THEN
      RAISE EXCEPTION 'Reverse the reservation settlement before voiding cash already credited to a contract.' USING ERRCODE='23514';
    END IF;
  END LOOP;
  PERFORM set_config('app.payment_correction','void_payment_record',true);
  PERFORM set_config('app.payment_allocation_write','on',true);
  UPDATE public.transactions SET status='voided',voided_at=now(),voided_by=v_actor,void_reason=btrim(p_reason)
  WHERE id=v_payment.id RETURNING * INTO v_updated;
  INSERT INTO public.transaction_allocations(
    tenant_id,transaction_id,customer_id,allocation_kind,amount,currency,scope_kind,project_id,phase_id,
    contract_id,reservation_id,fee_charge_id,allocation_reason,reversal_of_allocation_id,created_by
  )
  SELECT a.tenant_id,a.transaction_id,a.customer_id,'reversal',-a.amount,a.currency,a.scope_kind,a.project_id,a.phase_id,
    a.contract_id,a.reservation_id,a.fee_charge_id,a.allocation_reason,a.id,v_actor
  FROM public.transaction_allocations a
  WHERE a.transaction_id=v_payment.id AND a.tenant_id=v_payment.tenant_id
    AND a.allocation_kind IN ('applied','unallocated')
    AND NOT EXISTS (SELECT 1 FROM public.transaction_allocations r WHERE r.reversal_of_allocation_id=a.id);
  INSERT INTO public.audit_events(
    tenant_id,target_tenant_id,entity_type,entity_id,action,title,summary,before_data,after_data,metadata,actor_user_id
  ) VALUES (
    v_payment.tenant_id,v_payment.tenant_id,'payment',v_payment.id::text,'voided','Payment voided',
    'The receipt remains in history; exact allocation rows were reversed atomically.',
    to_jsonb(v_payment),to_jsonb(v_updated),
    jsonb_build_object('amount',v_payment.amount,'transaction_type',v_payment.transaction_type,'collection_method',v_payment.collection_method,'reason',btrim(p_reason)),v_actor
  );
  RETURN v_updated;
END;
$function$;
REVOKE ALL ON FUNCTION public.void_payment_record(bigint,text) FROM PUBLIC, anon, service_role;
