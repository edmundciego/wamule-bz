CREATE OR REPLACE FUNCTION public.guard_payment_request_scope_m75()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_contract public.contracts%ROWTYPE;
  v_fee public.fee_charges%ROWTYPE;
BEGIN
  IF TG_OP='UPDATE' AND (NEW.tenant_id IS DISTINCT FROM OLD.tenant_id OR NEW.customer_id IS DISTINCT FROM OLD.customer_id
    OR NEW.contract_id IS DISTINCT FROM OLD.contract_id OR NEW.fee_charge_id IS DISTINCT FROM OLD.fee_charge_id
    OR NEW.project_id IS DISTINCT FROM OLD.project_id OR NEW.phase_id IS DISTINCT FROM OLD.phase_id
    OR NEW.scope_kind IS DISTINCT FROM OLD.scope_kind OR NEW.currency IS DISTINCT FROM OLD.currency) THEN
    RAISE EXCEPTION 'A payment request obligation and scope are immutable; create a corrected reminder.' USING ERRCODE='23514';
  END IF;
  IF TG_OP='INSERT' THEN
    IF num_nonnulls(NEW.contract_id,NEW.fee_charge_id)<>1 THEN
      RAISE EXCEPTION 'A new reminder must point to one assessed contract or fee-charge obligation.' USING ERRCODE='23514';
    END IF;
    IF NEW.contract_id IS NOT NULL THEN
      SELECT * INTO v_contract FROM public.contracts c WHERE c.id=NEW.contract_id;
      IF NOT FOUND OR v_contract.tenant_id IS DISTINCT FROM NEW.tenant_id OR v_contract.customer_id IS DISTINCT FROM NEW.customer_id
        OR v_contract.project_id IS NULL OR v_contract.phase_id IS NULL THEN
        RAISE EXCEPTION 'Reminder contract must have the same customer and verified phase scope.' USING ERRCODE='23514';
      END IF;
      NEW.project_id:=v_contract.project_id; NEW.phase_id:=v_contract.phase_id;
      NEW.scope_kind:=CASE WHEN v_contract.phase_id IS NULL THEN 'unallocated' ELSE 'phase' END;
      NEW.currency:=v_contract.currency;
    ELSE
      SELECT * INTO v_fee FROM public.fee_charges f WHERE f.id=NEW.fee_charge_id;
      IF NOT FOUND OR v_fee.tenant_id IS DISTINCT FROM NEW.tenant_id OR v_fee.customer_id IS DISTINCT FROM NEW.customer_id THEN
        RAISE EXCEPTION 'Reminder fee charge must belong to the same tenant and customer.' USING ERRCODE='23514';
      END IF;
      NEW.project_id:=v_fee.project_id; NEW.phase_id:=v_fee.phase_id;
      NEW.scope_kind:=v_fee.scope_kind;
      NEW.currency:=v_fee.currency;
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;
