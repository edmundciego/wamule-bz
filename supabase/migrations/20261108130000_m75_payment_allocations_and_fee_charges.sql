CREATE OR REPLACE FUNCTION public.settle_reservation_deposit_v1(
  p_reservation_id uuid,p_contract_id bigint,p_amount numeric,p_currency text,
  p_idempotency_key uuid,p_reason text
)
RETURNS public.reservation_contract_settlements
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_profile_tenant uuid;
  v_reservation public.lot_reservations%ROWTYPE;
  v_contract public.contracts%ROWTYPE;
  v_existing_key public.reservation_contract_settlements%ROWTYPE;
  v_settlement public.reservation_contract_settlements%ROWTYPE;
  v_cash numeric(12,2);
  v_settled numeric(12,2);
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'An authenticated Tenant Admin or Super Admin is required.' USING ERRCODE='42501'; END IF;
  SELECT ap.role::text,ap.tenant_id INTO v_role,v_profile_tenant
  FROM public.admin_profiles ap WHERE ap.user_id=v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin') THEN RAISE EXCEPTION 'Only an Admin can settle a reservation deposit.' USING ERRCODE='42501'; END IF;
  IF p_idempotency_key IS NULL OR p_amount IS NULL OR p_amount<=0 OR p_currency !~ '^[A-Z]{3}$'
     OR NULLIF(btrim(p_reason),'') IS NULL THEN
    RAISE EXCEPTION 'A positive amount, currency, idempotency key and reason are required.' USING ERRCODE='23514';
  END IF;

  SELECT * INTO v_existing_key FROM public.reservation_contract_settlements s
  WHERE s.idempotency_key=p_idempotency_key;
  IF FOUND THEN
    IF v_existing_key.reservation_id IS DISTINCT FROM p_reservation_id
       OR v_existing_key.contract_id IS DISTINCT FROM p_contract_id
       OR v_existing_key.amount IS DISTINCT FROM p_amount
       OR v_existing_key.currency IS DISTINCT FROM p_currency THEN
      RAISE EXCEPTION 'The idempotency key was already used for a different settlement.' USING ERRCODE='23514';
    END IF;
    IF NOT public.user_has_tenant_access(v_existing_key.tenant_id)
       OR (v_role='Admin' AND v_profile_tenant IS DISTINCT FROM v_existing_key.tenant_id) THEN
      RAISE EXCEPTION 'The settlement is outside the actor’s verified tenant.' USING ERRCODE='42501';
    END IF;
    RETURN v_existing_key;
  END IF;

  SELECT * INTO v_reservation FROM public.lot_reservations r
  WHERE r.id=p_reservation_id FOR UPDATE;
  IF NOT FOUND OR v_reservation.project_id IS NULL OR v_reservation.phase_id IS NULL
     OR v_reservation.customer_id IS NULL OR v_reservation.currency IS DISTINCT FROM p_currency THEN
    RAISE EXCEPTION 'The reservation must have verified scope, customer and matching currency.' USING ERRCODE='23514';
  END IF;
  IF NOT public.user_has_tenant_access(v_reservation.tenant_id)
     OR (v_role='Admin' AND v_profile_tenant IS DISTINCT FROM v_reservation.tenant_id) THEN
    RAISE EXCEPTION 'The reservation is outside the actor’s verified tenant.' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_contract FROM public.contracts c
  WHERE c.id=p_contract_id FOR UPDATE;
  IF NOT FOUND OR v_contract.tenant_id IS DISTINCT FROM v_reservation.tenant_id
     OR v_contract.customer_id IS DISTINCT FROM v_reservation.customer_id
     OR v_contract.project_id IS DISTINCT FROM v_reservation.project_id
     OR v_contract.phase_id IS DISTINCT FROM v_reservation.phase_id
     OR v_contract.parcel_id IS DISTINCT FROM v_reservation.parcel_id
     OR v_contract.reservation_id IS DISTINCT FROM v_reservation.id
     OR v_contract.currency IS DISTINCT FROM p_currency
     OR v_contract.status<>'active' OR v_contract.is_active IS NOT TRUE THEN
    RAISE EXCEPTION 'The reservation and active contract must be the same verified sale and currency.' USING ERRCODE='23514';
  END IF;

  SELECT COALESCE(sum(a.amount),0) INTO v_cash
  FROM public.transaction_allocations a
  JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
  WHERE a.reservation_id=v_reservation.id AND a.tenant_id=v_reservation.tenant_id
    AND a.currency=p_currency AND a.allocation_kind IN ('applied','reversal') AND t.status='posted';
  SELECT COALESCE(sum(s.amount),0) INTO v_settled
  FROM public.reservation_contract_settlements s
  WHERE s.reservation_id=v_reservation.id AND s.tenant_id=v_reservation.tenant_id AND s.currency=p_currency;
  IF v_cash-v_settled<p_amount THEN
    RAISE EXCEPTION 'Settlement cannot exceed posted reservation cash that has not already been credited.' USING ERRCODE='23514';
  END IF;

  INSERT INTO public.reservation_contract_settlements(
    idempotency_key,tenant_id,customer_id,project_id,phase_id,reservation_id,contract_id,amount,currency,reason,settled_by
  ) VALUES (
    p_idempotency_key,v_reservation.tenant_id,v_reservation.customer_id,v_reservation.project_id,v_reservation.phase_id,
    v_reservation.id,v_contract.id,p_amount,p_currency,btrim(p_reason),v_actor
  ) RETURNING * INTO v_settlement;
  INSERT INTO public.audit_events(
    tenant_id,target_tenant_id,target_project_id,target_phase_id,entity_type,entity_id,action,title,summary,metadata,actor_user_id
  ) VALUES (
    v_reservation.tenant_id,v_reservation.tenant_id,v_reservation.project_id,v_reservation.phase_id,
    'reservation',v_reservation.id::text,'created','Reservation deposit settled',
    'A posted reservation deposit of '||p_amount::text||' '||p_currency||' was credited once to its verified contract balance.',
    jsonb_build_object('primary_reservation_id',v_reservation.id,'contract_id',v_contract.id,'amount',p_amount,'currency',p_currency),v_actor
  );
  RETURN v_settlement;
END;
$function$;
REVOKE ALL ON FUNCTION public.settle_reservation_deposit_v1(uuid,bigint,numeric,text,uuid,text) FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.settle_reservation_deposit_v1(uuid,bigint,numeric,text,uuid,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.reverse_reservation_contract_settlement_v1(
  p_settlement_id bigint,p_idempotency_key uuid,p_reason text
)
RETURNS public.reservation_contract_settlements
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_profile_tenant uuid;
  v_original public.reservation_contract_settlements%ROWTYPE;
  v_existing public.reservation_contract_settlements%ROWTYPE;
  v_reversal public.reservation_contract_settlements%ROWTYPE;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'An authenticated Tenant Admin or Super Admin is required.' USING ERRCODE='42501'; END IF;
  SELECT ap.role::text,ap.tenant_id INTO v_role,v_profile_tenant
  FROM public.admin_profiles ap WHERE ap.user_id=v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin') THEN RAISE EXCEPTION 'Only an Admin can reverse a reservation settlement.' USING ERRCODE='42501'; END IF;
  IF p_idempotency_key IS NULL OR NULLIF(btrim(p_reason),'') IS NULL THEN
    RAISE EXCEPTION 'An idempotency key and reason are required.' USING ERRCODE='23514';
  END IF;
  SELECT * INTO v_existing FROM public.reservation_contract_settlements s WHERE s.idempotency_key=p_idempotency_key;
  IF FOUND THEN
    IF v_existing.settlement_kind<>'reversal' OR v_existing.reverses_settlement_id IS DISTINCT FROM p_settlement_id THEN
      RAISE EXCEPTION 'The idempotency key was already used for another settlement operation.' USING ERRCODE='23514';
    END IF;
    IF NOT public.user_has_tenant_access(v_existing.tenant_id)
       OR (v_role='Admin' AND v_profile_tenant IS DISTINCT FROM v_existing.tenant_id) THEN
      RAISE EXCEPTION 'The settlement is outside the actor’s verified tenant.' USING ERRCODE='42501';
    END IF;
    RETURN v_existing;
  END IF;
  SELECT * INTO v_original FROM public.reservation_contract_settlements s
  WHERE s.id=p_settlement_id AND s.settlement_kind='credit' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'An active settlement credit is required.' USING ERRCODE='23514'; END IF;
  IF NOT public.user_has_tenant_access(v_original.tenant_id)
     OR (v_role='Admin' AND v_profile_tenant IS DISTINCT FROM v_original.tenant_id) THEN
    RAISE EXCEPTION 'The settlement is outside the actor’s verified tenant.' USING ERRCODE='42501';
  END IF;
  IF EXISTS (SELECT 1 FROM public.reservation_contract_settlements s WHERE s.reverses_settlement_id=v_original.id) THEN
