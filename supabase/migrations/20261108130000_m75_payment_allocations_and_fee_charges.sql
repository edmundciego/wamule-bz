CREATE OR REPLACE FUNCTION public.guard_transaction_allocation_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_original public.transaction_allocations%ROWTYPE;
  v_parent public.transactions%ROWTYPE;
  v_scope_kind text;
  v_project uuid;
  v_phase uuid;
  v_currency text;
  v_customer bigint;
  v_tenant uuid;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'Payment allocations are append-only.' USING ERRCODE = '42501';
  END IF;
  IF COALESCE(current_setting('app.payment_allocation_write', true), '') <> 'on' THEN
    RAISE EXCEPTION 'Payment allocations can be written only by a validated payment operation.' USING ERRCODE = '42501';
  END IF;
  SELECT t.* INTO v_parent FROM public.transactions t
  WHERE t.id = NEW.transaction_id AND t.tenant_id = NEW.tenant_id AND t.customer_id = NEW.customer_id
  FOR KEY SHARE;
  IF NOT FOUND OR v_parent.status NOT IN ('posted', 'voided') THEN
    RAISE EXCEPTION 'Allocation must belong to a posted or voided receipt in the same tenant and customer.' USING ERRCODE = '23514';
  END IF;
  IF NEW.allocation_kind = 'reversal' THEN
    SELECT a.* INTO v_original FROM public.transaction_allocations a
    WHERE a.id = NEW.reversal_of_allocation_id
      AND a.tenant_id = NEW.tenant_id AND a.transaction_id = NEW.transaction_id
    FOR KEY SHARE;
    IF NOT FOUND OR NEW.amount <> -v_original.amount
       OR NEW.currency IS DISTINCT FROM v_original.currency
       OR NEW.customer_id IS DISTINCT FROM v_original.customer_id
       OR NEW.scope_kind IS DISTINCT FROM v_original.scope_kind
       OR NEW.project_id IS DISTINCT FROM v_original.project_id
       OR NEW.phase_id IS DISTINCT FROM v_original.phase_id
       OR NEW.contract_id IS DISTINCT FROM v_original.contract_id
       OR NEW.reservation_id IS DISTINCT FROM v_original.reservation_id
       OR NEW.fee_charge_id IS DISTINCT FROM v_original.fee_charge_id THEN
      RAISE EXCEPTION 'A reversal must exactly mirror one original allocation.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;
  IF v_parent.status <> 'posted' OR v_parent.allocation_version <> 'allocations_v1'
     OR NEW.currency IS DISTINCT FROM v_parent.currency THEN
    RAISE EXCEPTION 'New allocations must match a current posted allocations_v1 receipt currency.' USING ERRCODE = '23514';
  END IF;
  IF NEW.allocation_kind = 'unallocated' THEN
    RETURN NEW;
  END IF;

  IF NEW.contract_id IS NOT NULL THEN
    SELECT c.tenant_id,c.customer_id,c.project_id,c.phase_id,c.currency
      INTO v_tenant,v_customer,v_project,v_phase,v_currency
    FROM public.contracts c WHERE c.id=NEW.contract_id;
  ELSIF NEW.reservation_id IS NOT NULL THEN
    SELECT r.tenant_id,r.customer_id,r.project_id,r.phase_id,r.currency
      INTO v_tenant,v_customer,v_project,v_phase,v_currency
    FROM public.lot_reservations r WHERE r.id=NEW.reservation_id;
  ELSE
    SELECT f.tenant_id,f.customer_id,f.project_id,f.phase_id,f.currency,f.scope_kind
      INTO v_tenant,v_customer,v_project,v_phase,v_currency,v_scope_kind
    FROM public.fee_charges f WHERE f.id=NEW.fee_charge_id;
  END IF;
  IF NOT FOUND OR v_tenant IS DISTINCT FROM NEW.tenant_id
     OR v_customer IS DISTINCT FROM NEW.customer_id
     OR v_project IS DISTINCT FROM NEW.project_id
     OR v_phase IS DISTINCT FROM NEW.phase_id
     OR v_currency IS DISTINCT FROM NEW.currency
     OR (NEW.contract_id IS NOT NULL AND NEW.scope_kind <> 'phase')
     OR (NEW.reservation_id IS NOT NULL AND NEW.scope_kind <> 'phase')
     OR (NEW.fee_charge_id IS NOT NULL AND v_scope_kind IS DISTINCT FROM NEW.scope_kind) THEN
    RAISE EXCEPTION 'Allocation target tenant, customer, project, phase and currency must match the verified obligation.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.guard_transaction_allocation_write() FROM PUBLIC, anon, authenticated, service_role;
DROP TRIGGER IF EXISTS transaction_allocations_m75_guard ON public.transaction_allocations;
CREATE TRIGGER transaction_allocations_m75_guard
BEFORE INSERT OR UPDATE OR DELETE ON public.transaction_allocations
FOR EACH ROW EXECUTE FUNCTION public.guard_transaction_allocation_write();

CREATE OR REPLACE FUNCTION public.assert_receipt_allocation_total()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_amount numeric;
  v_allocated numeric;
  v_original_count bigint;
  v_reversal_count bigint;
BEGIN
  IF NEW.status = 'posted' AND NEW.allocation_version = 'allocations_v1' THEN
    SELECT t.amount, COALESCE(sum(a.amount) FILTER (WHERE a.allocation_kind IN ('applied','unallocated')),0)
      INTO v_amount,v_allocated
    FROM public.transactions t
    LEFT JOIN public.transaction_allocations a
      ON a.transaction_id=t.id AND a.tenant_id=t.tenant_id
    WHERE t.id=NEW.id AND t.tenant_id=NEW.tenant_id
    GROUP BY t.amount;
    IF v_amount IS NULL OR v_allocated <> v_amount THEN
      RAISE EXCEPTION 'Posted receipt allocation total must equal the receipt amount.' USING ERRCODE = '23514';
    END IF;
  ELSIF NEW.status = 'voided' THEN
    SELECT t.amount, COALESCE(sum(a.amount),0),
           count(*) FILTER (WHERE a.allocation_kind IN ('applied','unallocated')),
           count(*) FILTER (WHERE a.allocation_kind='reversal')
      INTO v_amount,v_allocated,v_original_count,v_reversal_count
    FROM public.transactions t
    LEFT JOIN public.transaction_allocations a
      ON a.transaction_id=t.id AND a.tenant_id=t.tenant_id
    WHERE t.id=NEW.id AND t.tenant_id=NEW.tenant_id
    GROUP BY t.amount;
    IF v_amount IS NULL OR v_allocated <> 0 OR v_original_count <> v_reversal_count THEN
      RAISE EXCEPTION 'A voided receipt must have zero net allocations and one reversal per original allocation.' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NULL;
END;
$function$;
REVOKE ALL ON FUNCTION public.assert_receipt_allocation_total() FROM PUBLIC, anon, authenticated, service_role;
DROP TRIGGER IF EXISTS transactions_m75_allocation_total ON public.transactions;
CREATE CONSTRAINT TRIGGER transactions_m75_allocation_total
AFTER INSERT OR UPDATE ON public.transactions DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.assert_receipt_allocation_total();

CREATE OR REPLACE FUNCTION public.assess_fee_charge_v1(
  p_tenant_id uuid,
  p_customer_id bigint,
  p_fee_type_id bigint,
  p_amount numeric,
  p_currency text,
  p_scope_kind text,
  p_project_id uuid,
  p_phase_id uuid,
  p_contract_id bigint,
  p_reservation_id uuid,
  p_due_date date,
  p_description text
)
RETURNS public.fee_charges
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_actor_tenant uuid;
  v_customer_tenant uuid;
  v_fee public.fee_types%ROWTYPE;
  v_contract public.contracts%ROWTYPE;
  v_reservation public.lot_reservations%ROWTYPE;
  v_charge public.fee_charges%ROWTYPE;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'An authenticated Tenant Admin or Super Admin is required.' USING ERRCODE='42501'; END IF;
  SELECT ap.role::text,ap.tenant_id INTO v_role,v_actor_tenant
  FROM public.admin_profiles ap WHERE ap.user_id=v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin') THEN RAISE EXCEPTION 'Only an Admin can assess a customer fee.' USING ERRCODE='42501'; END IF;
  IF p_tenant_id IS NULL OR NOT public.user_has_tenant_access(p_tenant_id)
     OR (v_role='Admin' AND v_actor_tenant IS DISTINCT FROM p_tenant_id) THEN
    RAISE EXCEPTION 'The target tenant is outside the verified Admin workspace.' USING ERRCODE='42501';
  END IF;
  IF p_amount IS NULL OR p_amount<=0 OR p_currency !~ '^[A-Z]{3}$'
     OR NULLIF(btrim(p_description),'') IS NULL
     OR p_scope_kind NOT IN ('company','project','phase')
     OR num_nonnulls(p_contract_id,p_reservation_id)>1 THEN
    RAISE EXCEPTION 'A positive amount, currency, description, valid scope and at most one sale parent are required.' USING ERRCODE='23514';
  END IF;
  SELECT c.tenant_id INTO v_customer_tenant FROM public.customers c
  WHERE c.id=p_customer_id FOR KEY SHARE;
  IF NOT FOUND OR v_customer_tenant IS DISTINCT FROM p_tenant_id THEN
    RAISE EXCEPTION 'The fee customer must belong to the verified target tenant.' USING ERRCODE='23503';
  END IF;
  SELECT f.* INTO v_fee FROM public.fee_types f
  WHERE f.id=p_fee_type_id AND f.tenant_id=p_tenant_id AND f.is_active FOR KEY SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Select an active fee type from the target tenant.' USING ERRCODE='23503'; END IF;
  IF p_scope_kind='company' AND (p_project_id IS NOT NULL OR p_phase_id IS NOT NULL OR num_nonnulls(p_contract_id,p_reservation_id)>0) THEN
    RAISE EXCEPTION 'Company fees cannot carry an arbitrary project, phase or sale parent.' USING ERRCODE='23514';
  ELSIF p_scope_kind='project' AND (p_project_id IS NULL OR p_phase_id IS NOT NULL OR num_nonnulls(p_contract_id,p_reservation_id)>0) THEN
    RAISE EXCEPTION 'Project fees require the exact target project and no phase or sale parent.' USING ERRCODE='23514';
  ELSIF p_scope_kind='phase' AND (p_project_id IS NULL OR p_phase_id IS NULL) THEN
    RAISE EXCEPTION 'Phase fees require the exact target project and phase.' USING ERRCODE='23514';
  END IF;
  IF NOT public.workspace_scope_exists(p_tenant_id,p_project_id,p_phase_id) THEN
    RAISE EXCEPTION 'The requested fee scope does not belong to the target tenant/project.' USING ERRCODE='23514';
  END IF;
  IF p_scope_kind='phase' AND NOT public.workspace_scope_is_active(p_tenant_id,p_project_id,p_phase_id) THEN
    RAISE EXCEPTION 'A new phase fee can only be assessed for an active tenant and phase.' USING ERRCODE='23514';
  END IF;
  IF p_scope_kind<>'company' AND NOT EXISTS (
    SELECT 1 FROM public.organizations o WHERE o.id=p_tenant_id AND o.is_active
  ) THEN RAISE EXCEPTION 'A new fee cannot be assessed for a suspended tenant.' USING ERRCODE='23514'; END IF;

  IF p_contract_id IS NOT NULL THEN
    SELECT * INTO v_contract FROM public.contracts c WHERE c.id=p_contract_id FOR UPDATE;
    IF NOT FOUND OR v_contract.tenant_id IS DISTINCT FROM p_tenant_id OR v_contract.customer_id IS DISTINCT FROM p_customer_id
      OR v_contract.project_id IS DISTINCT FROM p_project_id OR v_contract.phase_id IS DISTINCT FROM p_phase_id
      OR v_contract.currency IS DISTINCT FROM p_currency OR v_contract.status<>'active' THEN
      RAISE EXCEPTION 'The fee contract must match the customer, active sale scope and currency.' USING ERRCODE='23514';
    END IF;
  ELSIF p_reservation_id IS NOT NULL THEN
    SELECT * INTO v_reservation FROM public.lot_reservations r WHERE r.id=p_reservation_id FOR UPDATE;
    IF NOT FOUND OR v_reservation.tenant_id IS DISTINCT FROM p_tenant_id OR v_reservation.customer_id IS DISTINCT FROM p_customer_id
      OR v_reservation.project_id IS DISTINCT FROM p_project_id OR v_reservation.phase_id IS DISTINCT FROM p_phase_id
      OR v_reservation.currency IS DISTINCT FROM p_currency THEN
      RAISE EXCEPTION 'The fee reservation must match the customer, sale scope and currency.' USING ERRCODE='23514';
    END IF;
  END IF;
  INSERT INTO public.fee_charges(
    tenant_id,customer_id,fee_type_id,amount,currency,scope_kind,project_id,phase_id,
    contract_id,reservation_id,due_date,description,assessed_by
  ) VALUES (
    p_tenant_id,p_customer_id,p_fee_type_id,p_amount,p_currency,p_scope_kind,p_project_id,p_phase_id,
    p_contract_id,p_reservation_id,p_due_date,btrim(p_description),v_actor
  ) RETURNING * INTO v_charge;
  INSERT INTO public.audit_events(
    tenant_id,target_tenant_id,target_project_id,target_phase_id,entity_type,action,title,summary,metadata,actor_user_id
  ) VALUES (
    p_tenant_id,p_tenant_id,p_project_id,p_phase_id,'system','created','Fee obligation assessed',
    'An Admin explicitly assessed a customer fee obligation.',
    jsonb_build_object('event_code','fee_charge_assessed','amount',p_amount,'currency',p_currency),v_actor
  );
  RETURN v_charge;
END;
$function$;
REVOKE ALL ON FUNCTION public.assess_fee_charge_v1(uuid,bigint,bigint,numeric,text,text,uuid,uuid,bigint,uuid,date,text) FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.assess_fee_charge_v1(uuid,bigint,bigint,numeric,text,text,uuid,uuid,bigint,uuid,date,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.record_payment_with_allocations_v1(
  p_customer_id bigint,
  p_amount numeric,
  p_currency text,
  p_transaction_type public.transaction_type,
  p_collection_method public.collection_method,
  p_bank_reference text,
  p_manual_receipt_number text,
  p_receipt_date date,
  p_receipt_issued_by text,
  p_receipt_notes text,
  p_notes text,
  p_reversal_of_transaction_id bigint,
  p_allocations jsonb
)
RETURNS public.transactions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_role text;
  v_actor_tenant uuid;
  v_tenant uuid;
  v_customer_tenant uuid;
  v_item jsonb;
  v_target record;
  v_contract public.contracts%ROWTYPE;
  v_reservation public.lot_reservations%ROWTYPE;
  v_fee public.fee_charges%ROWTYPE;
  v_fee_type public.fee_types%ROWTYPE;
  v_transaction public.transactions%ROWTYPE;
  v_amount numeric(12,2);
  v_allocated numeric(12,2);
  v_requested numeric(12,2);
  v_existing numeric(12,2);
  v_unallocated_reason text;
  v_contract_id bigint;
  v_count integer;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'An authenticated Tenant Admin or Super Admin is required.' USING ERRCODE='42501'; END IF;
  SELECT ap.role::text,ap.tenant_id INTO v_role,v_actor_tenant
  FROM public.admin_profiles ap WHERE ap.user_id=v_actor FOR SHARE;
  IF v_role NOT IN ('Admin','Super Admin') THEN RAISE EXCEPTION 'Only an Admin can post a receipt.' USING ERRCODE='42501'; END IF;
  IF p_amount IS NULL OR p_amount<=0 OR p_currency !~ '^[A-Z]{3}$' THEN
    RAISE EXCEPTION 'A positive receipt amount and configured three-letter currency are required.' USING ERRCODE='23514';
  END IF;
  IF p_transaction_type NOT IN ('Down Payment','Land Installment','Garbage Fee','Road Maintenance') THEN
    RAISE EXCEPTION 'Unsupported receipt type.' USING ERRCODE='23514';
  END IF;
  IF p_collection_method='Online Transfer' AND NULLIF(btrim(p_bank_reference),'') IS NULL THEN
    RAISE EXCEPTION 'Bank reference is required for an online transfer.' USING ERRCODE='23514';
  END IF;
  IF jsonb_typeof(p_allocations)<>'array' OR jsonb_array_length(p_allocations)=0 THEN
    RAISE EXCEPTION 'At least one explicit allocation or unallocated remainder is required.' USING ERRCODE='23514';
  END IF;
  SELECT c.tenant_id INTO v_customer_tenant FROM public.customers c WHERE c.id=p_customer_id FOR KEY SHARE;
  IF NOT FOUND OR NOT public.user_has_tenant_access(v_customer_tenant)
     OR (v_role='Admin' AND v_actor_tenant IS DISTINCT FROM v_customer_tenant) THEN
    RAISE EXCEPTION 'The selected customer is outside the actor’s verified tenant.' USING ERRCODE='42501';
  END IF;
  v_tenant := v_customer_tenant;
  SELECT count(*),COALESCE(sum((value->>'amount')::numeric),0)
    INTO v_count,v_allocated FROM jsonb_array_elements(p_allocations);
  IF v_allocated<>p_amount THEN
    RAISE EXCEPTION 'Applied and unallocated amounts must exactly equal the receipt.' USING ERRCODE='23514';
  END IF;

  IF p_transaction_type IN ('Garbage Fee','Road Maintenance') AND NOT EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_allocations) a
    WHERE a ? 'fee_charge_id' AND NULLIF(a->>'fee_charge_id','') IS NOT NULL
  ) THEN
    IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_allocations) a WHERE a->>'scope_kind'='unallocated') THEN
      RAISE EXCEPTION 'Fee receipts require an explicitly assessed fee charge or an explicit unallocated reason.' USING ERRCODE='23514';
    END IF;
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_allocations) LOOP
    v_amount := (v_item->>'amount')::numeric(12,2);
    IF v_amount<=0 OR upper(COALESCE(v_item->>'currency',''))<>p_currency THEN
      RAISE EXCEPTION 'Every allocation must have a positive amount in the same currency as the receipt.' USING ERRCODE='23514';
    END IF;
    IF v_item->>'scope_kind'='unallocated' THEN
      IF num_nonnulls(NULLIF(v_item->>'contract_id','')::bigint,NULLIF(v_item->>'reservation_id','')::uuid,NULLIF(v_item->>'fee_charge_id','')::bigint)>0
         OR NULLIF(v_item->>'project_id','') IS NOT NULL OR NULLIF(v_item->>'phase_id','') IS NOT NULL
         OR NULLIF(btrim(v_item->>'allocation_reason'),'') IS NULL THEN
        RAISE EXCEPTION 'Unallocated remainder requires a reason and cannot carry a guessed obligation or phase.' USING ERRCODE='23514';
      END IF;
      CONTINUE;
    END IF;
    IF num_nonnulls(NULLIF(v_item->>'contract_id','')::bigint,NULLIF(v_item->>'reservation_id','')::uuid,NULLIF(v_item->>'fee_charge_id','')::bigint)<>1 THEN
      RAISE EXCEPTION 'Each applied allocation must identify exactly one contract, reservation or fee charge.' USING ERRCODE='23514';
    END IF;
    IF NULLIF(v_item->>'contract_id','') IS NOT NULL THEN
      IF p_transaction_type NOT IN ('Down Payment','Land Installment') THEN
        RAISE EXCEPTION 'Fee receipts cannot be allocated to a land contract.' USING ERRCODE='23514';
      END IF;
      SELECT * INTO v_contract FROM public.contracts c
      WHERE c.id=(v_item->>'contract_id')::bigint FOR UPDATE;
      IF NOT FOUND OR v_contract.tenant_id IS DISTINCT FROM v_tenant OR v_contract.customer_id IS DISTINCT FROM p_customer_id
        OR v_contract.project_id IS NULL OR v_contract.phase_id IS NULL OR v_contract.currency IS DISTINCT FROM p_currency
        OR v_contract.status<>'active' THEN
        RAISE EXCEPTION 'The contract must be an active same-customer sale in the receipt currency with verified phase scope.' USING ERRCODE='23514';
      END IF;
      IF NULLIF(v_item->>'project_id','')::uuid IS DISTINCT FROM v_contract.project_id
        OR NULLIF(v_item->>'phase_id','')::uuid IS DISTINCT FROM v_contract.phase_id THEN
        RAISE EXCEPTION 'The supplied contract project/phase does not match the verified contract.' USING ERRCODE='23514';
      END IF;
      SELECT COALESCE(sum(a.amount),0) INTO v_existing
      FROM public.transaction_allocations a
      JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
      WHERE a.contract_id=v_contract.id AND a.tenant_id=v_tenant
        AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided');
      SELECT COALESCE(sum((a->>'amount')::numeric),0) INTO v_requested
      FROM jsonb_array_elements(p_allocations) a WHERE NULLIF(a->>'contract_id','')::bigint=v_contract.id;
      IF v_existing+v_requested>v_contract.final_purchase_price THEN
        RAISE EXCEPTION 'Contract allocations exceed the remaining contract principal; record any excess as unallocated.' USING ERRCODE='23514';
      END IF;
    ELSIF NULLIF(v_item->>'reservation_id','') IS NOT NULL THEN
      IF p_transaction_type NOT IN ('Down Payment','Land Installment') THEN
        RAISE EXCEPTION 'Fee receipts cannot be allocated to a reservation deposit.' USING ERRCODE='23514';
      END IF;
      SELECT * INTO v_reservation FROM public.lot_reservations r
      WHERE r.id=(v_item->>'reservation_id')::uuid FOR UPDATE;
      IF NOT FOUND OR v_reservation.tenant_id IS DISTINCT FROM v_tenant OR v_reservation.customer_id IS DISTINCT FROM p_customer_id
        OR v_reservation.project_id IS NULL OR v_reservation.phase_id IS NULL OR v_reservation.currency IS DISTINCT FROM p_currency THEN
        RAISE EXCEPTION 'The reservation must match the customer, verified sale phase and receipt currency.' USING ERRCODE='23514';
      END IF;
      IF NULLIF(v_item->>'project_id','')::uuid IS DISTINCT FROM v_reservation.project_id
        OR NULLIF(v_item->>'phase_id','')::uuid IS DISTINCT FROM v_reservation.phase_id THEN
        RAISE EXCEPTION 'The supplied reservation project/phase does not match its verified scope.' USING ERRCODE='23514';
      END IF;
      IF v_reservation.expected_deposit_amount IS NOT NULL THEN
        SELECT COALESCE(sum(a.amount),0) INTO v_existing
        FROM public.transaction_allocations a
        JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
        WHERE a.reservation_id=v_reservation.id AND a.tenant_id=v_tenant
          AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided');
        SELECT COALESCE(sum((a->>'amount')::numeric),0) INTO v_requested
        FROM jsonb_array_elements(p_allocations) a WHERE NULLIF(a->>'reservation_id','')::uuid=v_reservation.id;
        IF v_existing+v_requested>v_reservation.expected_deposit_amount THEN
          RAISE EXCEPTION 'Reservation allocations exceed the configured deposit expectation.' USING ERRCODE='23514';
        END IF;
      END IF;
    ELSE
      IF p_transaction_type NOT IN ('Garbage Fee','Road Maintenance') THEN
        RAISE EXCEPTION 'Land receipts cannot be allocated to a fee charge.' USING ERRCODE='23514';
      END IF;
      SELECT * INTO v_fee FROM public.fee_charges f
      WHERE f.id=(v_item->>'fee_charge_id')::bigint FOR UPDATE;
      SELECT * INTO v_fee_type FROM public.fee_types ft
      WHERE ft.id=v_fee.fee_type_id AND ft.tenant_id=v_fee.tenant_id;
      IF NOT FOUND OR v_fee.tenant_id IS DISTINCT FROM v_tenant OR v_fee.customer_id IS DISTINCT FROM p_customer_id
        OR v_fee.currency IS DISTINCT FROM p_currency OR v_fee.status<>'open'
        OR v_fee_type.name IS DISTINCT FROM p_transaction_type::text
        OR v_fee.scope_kind IS DISTINCT FROM v_item->>'scope_kind'
        OR v_fee.project_id IS DISTINCT FROM NULLIF(v_item->>'project_id','')::uuid
        OR v_fee.phase_id IS DISTINCT FROM NULLIF(v_item->>'phase_id','')::uuid THEN
        RAISE EXCEPTION 'The fee allocation must match the open charge, customer, exact scope and currency.' USING ERRCODE='23514';
      END IF;
      SELECT COALESCE(sum(a.amount),0) INTO v_existing
      FROM public.transaction_allocations a
      JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
      WHERE a.fee_charge_id=v_fee.id AND a.tenant_id=v_tenant
        AND a.allocation_kind IN ('applied','reversal') AND t.status IN ('posted','voided');
      SELECT COALESCE(sum((a->>'amount')::numeric),0) INTO v_requested
      FROM jsonb_array_elements(p_allocations) a WHERE NULLIF(a->>'fee_charge_id','')::bigint=v_fee.id;
      IF v_existing+v_requested>v_fee.amount THEN
        RAISE EXCEPTION 'Fee allocations exceed the assessed charge balance.' USING ERRCODE='23514';
      END IF;
    END IF;
  END LOOP;

  -- Keep the compatibility pointer only when the receipt has one complete
  -- contract allocation. Split/project/company/remainder receipts stay at
  -- tenant scope and are never inferred into a selected phase.
  IF v_count=1 AND NULLIF(p_allocations->0->>'contract_id','') IS NOT NULL
     AND (p_allocations->0->>'amount')::numeric=p_amount THEN
    v_contract_id := (p_allocations->0->>'contract_id')::bigint;
  END IF;
  IF p_reversal_of_transaction_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.transactions t WHERE t.id=p_reversal_of_transaction_id AND t.tenant_id=v_tenant
      AND t.customer_id=p_customer_id AND t.status='voided' AND t.currency IS NOT DISTINCT FROM p_currency
  ) THEN RAISE EXCEPTION 'A correction replacement must reference a voided same-customer receipt and currency.' USING ERRCODE='23514'; END IF;

  PERFORM set_config('app.payment_allocation_write','on',true);
  INSERT INTO public.transactions(
    tenant_id,customer_id,contract_id,amount,currency,allocation_version,transaction_type,collection_method,
    bank_reference,manual_receipt_number,receipt_date,receipt_issued_by,receipt_notes,notes,status,
    reversal_of_transaction_id,correction_notes,authorized_by
  ) VALUES (
    v_tenant,p_customer_id,v_contract_id,p_amount,p_currency,'allocations_v1',p_transaction_type,p_collection_method,
    p_bank_reference,p_manual_receipt_number,p_receipt_date,p_receipt_issued_by,p_receipt_notes,p_notes,'posted',
    p_reversal_of_transaction_id,CASE WHEN p_reversal_of_transaction_id IS NOT NULL THEN 'Corrected replacement for a voided payment.' ELSE NULL END,v_actor
  ) RETURNING * INTO v_transaction;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_allocations) LOOP
    IF v_item->>'scope_kind'='unallocated' THEN
      INSERT INTO public.transaction_allocations(
        tenant_id,transaction_id,customer_id,allocation_kind,amount,currency,scope_kind,
        allocation_reason,created_by
      ) VALUES (
        v_tenant,v_transaction.id,p_customer_id,'unallocated',(v_item->>'amount')::numeric,p_currency,'unallocated',
        btrim(v_item->>'allocation_reason'),v_actor
      );
    ELSE
      INSERT INTO public.transaction_allocations(
        tenant_id,transaction_id,customer_id,allocation_kind,amount,currency,scope_kind,
        project_id,phase_id,contract_id,reservation_id,fee_charge_id,created_by
      ) VALUES (
        v_tenant,v_transaction.id,p_customer_id,'applied',(v_item->>'amount')::numeric,p_currency,v_item->>'scope_kind',
        NULLIF(v_item->>'project_id','')::uuid,NULLIF(v_item->>'phase_id','')::uuid,
        NULLIF(v_item->>'contract_id','')::bigint,NULLIF(v_item->>'reservation_id','')::uuid,
        NULLIF(v_item->>'fee_charge_id','')::bigint,v_actor
      );
    END IF;
  END LOOP;

  INSERT INTO public.audit_events(
    tenant_id,target_tenant_id,entity_type,entity_id,action,title,summary,metadata,actor_user_id
  ) VALUES (
    v_tenant,v_tenant,'payment',v_transaction.id::text,'created','Payment recorded',
    'An authorized Admin posted a receipt with explicit obligation allocations.',
    jsonb_build_object('amount',p_amount,'transaction_type',p_transaction_type,'collection_method',p_collection_method),v_actor
  );
  RETURN v_transaction;
END;
$function$;
