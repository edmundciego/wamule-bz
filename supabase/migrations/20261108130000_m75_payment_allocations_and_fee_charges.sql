-- Read-only exact-phase ledger projection. It never exposes the parent receipt
-- amount for a split receipt; each row is only the current member's allocation.
CREATE OR REPLACE FUNCTION public.read_phase_payment_allocations_v1(
  p_tenant_id uuid,p_project_id uuid,p_phase_id uuid
)
RETURNS TABLE(
  allocation_id bigint,transaction_id bigint,customer_id bigint,project_id uuid,phase_id uuid,contract_id bigint,
  reservation_id uuid,fee_charge_id bigint,allocation_amount numeric,currency text,
  transaction_type text,receipt_date date,created_at timestamptz,allocation_kind text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_role text;
BEGIN
  SELECT ap.role::text INTO v_role FROM public.admin_profiles ap WHERE ap.user_id=auth.uid();
  IF v_role NOT IN ('Admin','Super Admin','Read Only')
     OR NOT public.user_has_project_access(p_tenant_id,p_project_id,p_phase_id) THEN
    RAISE EXCEPTION 'The selected exact phase is not available for finance reads.' USING ERRCODE='42501';
  END IF;
  RETURN QUERY
  SELECT a.id,a.transaction_id,a.customer_id,a.project_id,a.phase_id,a.contract_id,a.reservation_id,a.fee_charge_id,
    a.amount,a.currency,t.transaction_type::text,t.receipt_date,t.created_at,a.allocation_kind
  FROM public.transaction_allocations a
  JOIN public.transactions t ON t.id=a.transaction_id AND t.tenant_id=a.tenant_id
  WHERE a.tenant_id=p_tenant_id AND a.project_id=p_project_id AND a.phase_id=p_phase_id
    AND a.scope_kind='phase' AND t.status IN ('posted','voided')
  ORDER BY t.created_at DESC,a.id;
END;
